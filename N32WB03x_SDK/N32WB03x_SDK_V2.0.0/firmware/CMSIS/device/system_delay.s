 .text
.syntax unified
.thumb

/*跨介质跳转调用前的完整现场保护*/
.type system_delay_cycles, %function   //声明这是个函数
.global system_delay_cycles            //导出符号使得外部可见，即可导出函数也可导出全局变量

system_delay_cycles:
subs r0, #1
bne system_delay_cycles
bx lr

.end

