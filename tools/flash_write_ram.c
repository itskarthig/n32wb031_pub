/* ── Blob function types ─────────────────────────────────────────────────── */
typedef uint32_t (*erase_func_t)(uint32_t rel_addr);
typedef uint32_t (*write_func_t)(uint32_t rel_addr, uint8_t *data, uint32_t len);

#define FLASH_BASE    ((uint32_t)0x01000000)
#define PARAM_BASE    ((volatile uint32_t *)0x2000B800)
#define DATA_BASE     ((uint8_t *)0x20000000)
#define SECTOR_SIZE   ((uint32_t)0x1000)   /* 4 KB erase sector */
#define PAGE_SIZE     ((uint32_t)0x100)    /* 256 B write page  */

/* Forward declaration — called from naked entry via inline asm */
void do_flash(void);

/* ── Entry point ─────────────────────────────────────────────────────────── */
/* Named stub_entry (not main) to avoid compiler warnings about void main.   */
void __attribute__((naked, noreturn)) stub_entry(void)
{
    __asm volatile (
        "ldr r0, =0x2000BFFC \n"  /* SP = top of SRAM - 4, stub is at 0x2000B810 */
        "mov sp, r0          \n"
        "bl  do_flash        \n"
        "bkpt #0             \n"   /* halt → OpenOCD wait_halt returns */
    );
}

/* ── Flash operation ─────────────────────────────────────────────────────── */
void do_flash(void)
{
    volatile uint32_t *params = PARAM_BASE;
    uint32_t flash_addr    = params[0];
    uint32_t data_length   = params[1];
    uint32_t erase_sectors = params[2];
    uint8_t *src           = DATA_BASE;

    /* Function pointers into the Qflash blob (Thumb bit included) */
    erase_func_t erase = (erase_func_t)((uint32_t)_acCMD_BIN + 0xA0 + 1);
    write_func_t write = (write_func_t)((uint32_t)_acCMD_BIN + 0x134 + 1);

    /* Phase 1 — Erase */
    if (erase_sectors > 0) {
        uint32_t rel = flash_addr - FLASH_BASE;
        for (uint32_t i = 0; i < erase_sectors; i++) {
            uint32_t result = erase(rel);
            if (result != 0) {
                params[3] = 0x10000000 | i;   /* error: erase failed at sector i */
                return;
            }
            rel += SECTOR_SIZE;
        }
    }

    /* Phase 2 — Write in 256-byte pages */
    if (data_length > 0) {
        uint32_t rel    = flash_addr - FLASH_BASE;
        uint32_t offset = 0;

        while (offset < data_length) {
            uint32_t chunk = data_length - offset;
            if (chunk > PAGE_SIZE) chunk = PAGE_SIZE;

            uint32_t result = write(rel, src + offset, chunk);
            if (result != 0) {
                params[3] = 0x20000000 | (offset >> 8);  /* error: write failed at page */
                return;
            }
            rel    += PAGE_SIZE;
            offset += PAGE_SIZE;
        }
    }

    params[3] = 0;  /* success */
}
