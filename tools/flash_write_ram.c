/*
 * flash_write_ram.c — RAM-resident flash programmer for N32WB031
 *
 * Runs entirely from SRAM. OpenOCD loads this ELF to 0x2000B000, sets up
 * a parameter block, loads firmware data to 0x20000000, then resumes
 * execution. The stub uses the SDK's own Qflash binary blob to erase
 * sectors and write pages via the proprietary Qflash controller.
 *
 * RAM layout (set by flash_stub.ld and openocd/flash_n32.tcl):
 *   0x20000000  firmware data  (loaded by OpenOCD, up to 47 KB)
 *   0x2000B800  parameter block (16 bytes, see below)
 *   0x2000B810  this ELF  (.text + .rodata including blob)
 *   0x2000BFFC  initial SP
 *
 * Parameter block at 0x2000B800:
 *   [+0x00]  flash_addr    (uint32_t) — absolute flash address to program
 *   [+0x04]  data_length   (uint32_t) — bytes to write (0 = erase only)
 *   [+0x08]  erase_sectors (uint32_t) — 4 KB sectors to erase (0 = write only)
 *   [+0x0C]  status        (uint32_t) — OUT: 0=success, nonzero=error code
 *
 * Build:
 *   arm-none-eabi-gcc -mcpu=cortex-m0 -mthumb -Os -nostdlib \
 *     -T tools/flash_stub.ld -e main \
 *     -o tools/flash_write_ram.elf tools/flash_write_ram.c
 */

